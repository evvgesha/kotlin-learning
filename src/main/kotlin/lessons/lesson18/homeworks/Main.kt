package lessons.lesson18.homeworks

fun main() {
    println("=== 1. ХОЛОДИЛЬНИК ===")
    val fridge = Refrigerator()
    fridge.setTemperature(4) // Проверка: выключенный не должен менять температуру
    fridge.powerOn()
    fridge.open()
    fridge.setTemperature(4)
    fridge.programAction("Быстрая заморозка")
    fridge.execute()
    fridge.close()
    fridge.clean()
    fridge.powerOff()

    println()
    println("=== 2. СТИРАЛЬНАЯ МАШИНА ===")
    val washer = WashingMachine()
    washer.powerOn()
    washer.open()
    washer.close()
    washer.connectToWaterSupply()
    washer.getWater(15)
    washer.setTemperature(60)
    washer.programAction("Стирка хлопка")
    washer.setTimer(45)
    washer.execute()
    washer.connectToDrain()
    washer.drain()
    washer.powerOff()

    println()
    println("=== 3. ЧАЙНИК ===")
    val kettle = Kettle()
    kettle.open()
    kettle.fillWater(1200)
    kettle.close()
    kettle.powerOn()
    kettle.setTemperature(100)
    kettle.startMonitoring()
    kettle.programAction("Кипячение")
    kettle.execute()
    kettle.getWater(300)
    kettle.powerOff()

    println()
    println("=== 4. ДУХОВКА ===")
    val oven = Oven()
    oven.powerOn()
    oven.open()
    oven.close()
    oven.emitLight()
    oven.setTemperature(180)
    oven.programAction("Выпечка пирога")
    oven.setTimer(40)
    oven.execute()
    oven.completeLiteEmission()
    oven.powerOff()
}
